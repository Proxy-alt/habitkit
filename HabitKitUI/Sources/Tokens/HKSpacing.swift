import CoreFoundation

// MARK: - HabitKit Spacing scale

/// A set of standardised spacing constants used throughout HabitKitUI.
public enum HKSpacing {
    /// 4 pt — tight gap between closely related elements.
    public static let xs: CGFloat  =  4

    /// 8 pt — small internal padding / icon-to-label gap.
    public static let sm: CGFloat  =  8

    /// 16 pt — standard content padding.
    public static let md: CGFloat  = 16

    /// 24 pt — section separator / card padding.
    public static let lg: CGFloat  = 24

    /// 32 pt — large group spacing.
    public static let xl: CGFloat  = 32

    /// 48 pt — screen-level vertical rhythm.
    public static let xxl: CGFloat = 48
}
